export function webHtmlLang(locale) {
  return locale === 'zh' ? 'zh-CN' : 'en';
}

export function resolveWebLocale(stored, languages) {
  const pick = (value) => {
    const tag = String(value ?? '').trim().toLowerCase().replaceAll('_', '-');
    if (tag.startsWith('zh')) return 'zh';
    if (tag.startsWith('en')) return 'en';
    return '';
  };
  const saved = pick(stored);
  if (saved) return saved;
  const list = Array.isArray(languages) ? languages : (languages ? [languages] : []);
  for (const entry of list) {
    const hit = pick(entry);
    if (hit) return hit;
  }
  return 'en';
}
